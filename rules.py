def extract_all_conditions(rules):
    """Извлекает все уникальные условия из списка правил."""
    condition_set = set()
    for rule in rules:
        for cond in rule["conditions"]:
            condition_set.add(cond)
    return sorted(condition_set)


def get_categories(rules, device=None):
    """Возвращает список категорий (для возможной группировки в интерфейсе)."""
    cats = {}
    for rule in rules:
        if device and rule["device"] not in (device, "both"):
            continue
        cat = rule.get("category", "Прочее")
        cats.setdefault(cat, 0)
        cats[cat] += 1
    return cats
